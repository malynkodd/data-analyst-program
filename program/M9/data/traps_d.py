def trap_40_missing_not_at_random():
    """Пропуски в данных не случайны и сами по себе несут информацию."""
    random.seed(SEED + 3)
    n = 500
    satisfaction = [random.gauss(7, 2) for _ in range(n)]
    responded = [s > 4 or random.random() < 0.2 for s in satisfaction]  # недовольные реже отвечают
    observed = [s for s, r in zip(satisfaction, responded) if r]
    return {
        "вопрос": f"Средняя оценка по {len(observed)} ответившим — "
                  f"{statistics.mean(observed):.2f} из 10. Отсутствующие оценки можно "
                  f"игнорировать как случайный шум?",
        "датасет": f"n={n}, ответили {len(observed)}, истинное среднее по всем "
                   f"{statistics.mean(satisfaction):.2f}, по ответившим "
                   f"{statistics.mean(observed):.2f}",
        "неверный_ответ": "да, недостающие ответы не смещают среднее",
        "правильный_ответ": f"пропуски здесь не случайны (Missing Not At Random): "
                           f"недовольные реже отвечают на опрос об удовлетворённости — "
                           f"среднее по ответившим ({statistics.mean(observed):.2f}) "
                           f"выше истинного среднего по всем ({statistics.mean(satisfaction):.2f}); "
                           f"игнорирование пропусков как «случайных» завышает результат",
        "число": round(statistics.mean(observed) - statistics.mean(satisfaction), 2),
    }


