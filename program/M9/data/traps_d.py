def trap_33_berksons_paradox():
    """Коллайдер: отбор по одному признаку создаёт ложную отрицательную связь двух других."""
    random.seed(SEED + 1)
    n = 2000
    talent = [random.gauss(0, 1) for _ in range(n)]
    looks = [random.gauss(0, 1) for _ in range(n)]
    admitted = [(t + l) > 1.0 for t, l in zip(talent, looks)]  # отбор по сумме
    adm_talent = [t for t, a in zip(talent, admitted) if a]
    adm_looks = [l for l, a in zip(looks, admitted) if a]
    mean_t, mean_l = statistics.mean(adm_talent), statistics.mean(adm_looks)
    cov = sum((t-mean_t)*(l-mean_l) for t, l in zip(adm_talent, adm_looks)) / len(adm_talent)
    r_admitted = cov / (statistics.pstdev(adm_talent) * statistics.pstdev(adm_looks))
    mean_t0, mean_l0 = statistics.mean(talent), statistics.mean(looks)
    cov0 = sum((t-mean_t0)*(l-mean_l0) for t, l in zip(talent, looks)) / n
    r_all = cov0 / (statistics.pstdev(talent) * statistics.pstdev(looks))
    return {
        "вопрос": f"Среди отобранных в программу стажировки (по сумме «талант + "
                  f"харизма» выше порога) талант и харизма отрицательно коррелируют "
                  f"(r={r_admitted:.2f}). Значит, одно мешает другому?",
        "датасет": f"n={n}, до отбора r(талант,харизма)={r_all:.2f}, среди "
                   f"{len(adm_talent)} отобранных r={r_admitted:.2f}",
        "неверный_ответ": "да, высокий талант компенсируется низкой харизмой и наоборот",
        "правильный_ответ": f"нет прямой связи между качествами (r={r_all:.2f} до "
                           f"отбора, около нуля) — отрицательная корреляция возникает "
                           f"из-за самого правила отбора (парадокс Берксона): если в "
                           f"выборку попадают те, у кого сумма выше порога, низкий "
                           f"талант среди отобранных компенсировался высокой харизмой "
                           f"— искусственная связь создана процедурой отбора, а не "
                           f"качествами самими по себе",
        "число": round(r_admitted, 2),
    }


