def trap_35_spurious_trend():
    """Общий возрастающий тренд у двух независимых рядов создаёт иллюзию связи."""
    random.seed(SEED + 2)
    n = 30
    trend = list(range(n))
    series_a = [10 + 2*t + random.gauss(0, 3) for t in trend]
    series_b = [20 + 1.8*t + random.gauss(0, 4) for t in trend]  # растёт по своей причине
    mean_a, mean_b = statistics.mean(series_a), statistics.mean(series_b)
    cov = sum((a-mean_a)*(b-mean_b) for a, b in zip(series_a, series_b)) / n
    r = cov / (statistics.pstdev(series_a) * statistics.pstdev(series_b))
    return {
        "вопрос": f"Число пользователей приложения и продажи мороженого в стране "
                  f"коррелируют за последние 30 месяцев (r={r:.2f}). Есть связь?",
        "датасет": f"n=30 месяцев, r={r:.2f}, оба ряда имеют собственный тренд во времени",
        "неверный_ответ": "да, связь заметная — стоит изучить механизм",
        "правильный_ответ": f"ложная корреляция за счёт общего временного тренда: любые "
                           f"два ряда, монотонно меняющиеся во времени по своим "
                           f"причинам, дадут высокую корреляцию (здесь r={r:.2f}) без "
                           f"содержательной связи — проверка на ложность: включить время "
                           f"как контрольную переменную или смотреть на корреляцию "
                           f"приростов, а не уровней",
        "число": round(r, 2),
    }


def trap_36_weighted_vs_simple_average():
    """Среднее по группам ≠ среднее по всем наблюдениям при разных размерах групп."""
    group_a = (4.8, 1000)  # (среднее, n)
    group_b = (3.2, 50)
    simple_avg = (group_a[0] + group_b[0]) / 2
    weighted_avg = (group_a[0]*group_a[1] + group_b[0]*group_b[1]) / (group_a[1]+group_b[1])
    return {
        "вопрос": f"Оценка сервиса A — {group_a[0]} (n={group_a[1]}), оценка сервиса "
                  f"B — {group_b[0]} (n={group_b[1]}). Средняя оценка платформы — "
                  f"{simple_avg:.2f}?",
        "датасет": f"простое среднее {simple_avg:.2f}, взвешенное по числу отзывов "
                   f"{weighted_avg:.2f}",
        "неверный_ответ": f"да, {simple_avg:.2f} — среднее двух чисел",
        "правильный_ответ": f"нет, если речь о средней оценке платформы в целом — нужно "
                           f"взвесить по числу отзывов: {weighted_avg:.2f}, а не "
                           f"{simple_avg:.2f}. Простое среднее двух средних придаёт "
                           f"сервису B (50 отзывов) тот же вес, что сервису A (1000 "
                           f"отзывов) — вес B завышен в 10.5 раза относительно его "
                           f"доли в общем числе отзывов (50 из 1050, то есть 4.8%, а "
                           f"не 50%)",
        "число": round(weighted_avg - simple_avg, 2),
    }


def trap_37_denominator_change():
    """Рост показателя вызван изменением базы расчёта, не сути."""
    month1 = (400, 10000)  # (события, база)
    month2 = (420, 8000)   # база сократилась (например, изменилось определение активного пользователя)
    rate1 = month1[0]/month1[1]
    rate2 = month2[0]/month2[1]
    return {
        "вопрос": f"Доля конверсии выросла с {rate1:.1%} до {rate2:.1%}. Продукт стал "
                  f"лучше конвертировать?",
        "датасет": f"месяц 1: {month1[0]}/{month1[1]}={rate1:.1%}; "
                   f"месяц 2: {month2[0]}/{month2[1]}={rate2:.1%} (число конверсий "
                   f"почти не изменилось — {month1[0]} против {month2[0]})",
        "неверный_ответ": f"да, доля выросла на {rate2-rate1:.1%}",
        "правильный_ответ": f"числитель почти не изменился ({month1[0]} против "
                           f"{month2[0]}), а знаменатель сократился — рост доли вызван "
                           f"уменьшением базы (например, изменилось определение "
                           f"«активного пользователя»), а не улучшением самой "
                           f"конверсии; сравнение долей требует проверки, что база "
                           f"считается одинаково в обоих периодах",
        "число": round(rate2 - rate1, 4),
    }


def trap_38_outlier_driven_mean():
    """Одно крупное значение определяет среднее группы из немногих."""
    values = [120, 135, 110, 128, 4500]
    mean_with = statistics.mean(values)
    mean_without = statistics.mean(values[:-1])
    median_with = statistics.median(values)
    return {
        "вопрос": f"Средний чек группы из 5 клиентов — {mean_with:.0f} грн. Это "
                  f"типичный чек этой группы?",
        "датасет": f"чеки: {values}",
        "неверный_ответ": f"да, типичный чек — {mean_with:.0f} грн",
        "правильный_ответ": f"нет — один чек на 4500 грн сдвигает среднее с "
                           f"{mean_without:.0f} (без него) до {mean_with:.0f}; медиана "
                           f"({median_with}) устойчивее к этому единичному значению и "
                           f"лучше описывает «типичного» клиента группы",
        "число": round(mean_with - mean_without, 0),
    }


