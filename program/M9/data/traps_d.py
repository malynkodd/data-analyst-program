"""Ловушки группы D — корреляция, причинность, агрегация (step-04.md, 10 штук)."""

import random
import statistics
from math import sqrt

SEED = 20260826


def trap_31_confounding():
    """Классический конфаундер: третья переменная объясняет обе."""
    random.seed(SEED)
    n = 40
    temperature = [random.uniform(15, 35) for _ in range(n)]
    ice_cream = [50 + 3*t + random.gauss(0, 15) for t in temperature]
    drownings = [1 + 0.3*t + random.gauss(0, 3) for t in temperature]
    mean_x, mean_y = statistics.mean(ice_cream), statistics.mean(drownings)
    cov = sum((x-mean_x)*(y-mean_y) for x, y in zip(ice_cream, drownings)) / n
    r = cov / (statistics.pstdev(ice_cream) * statistics.pstdev(drownings))
    return {
        "вопрос": f"Продажи мороженого коррелируют с числом утоплений (r={r:.2f}). "
                  f"Мороженое опасно?",
        "датасет": f"n={n} дней, r(мороженое, утопления)={r:.2f}",
        "неверный_ответ": "да, корреляция говорит о причинной связи",
        "правильный_ответ": "нет — обе переменные вызваны третьей: температурой. В "
                           "жару больше едят мороженого и больше купаются (что "
                           "повышает риск утоплений) — прямой связи между мороженым и "
                           "утоплениями нет, температура — конфаундер",
        "число": round(r, 2),
    }


