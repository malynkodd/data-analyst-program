def trap_19_ratio_metric_variance():
    """Отношение двух шумных величин может быть куда более волатильно, чем каждая по отдельности."""
    random.seed(SEED + 5)
    revenue = [random.gauss(100000, 15000) for _ in range(30)]
    users = [random.gauss(1000, 50) for _ in range(30)]
    arpu = [r/u for r, u in zip(revenue, users)]
    cv_revenue = statistics.pstdev(revenue) / statistics.mean(revenue)
    cv_arpu = statistics.pstdev(arpu) / statistics.mean(arpu)
    return {
        "вопрос": "ARPU (выручка/пользователи) скачет сильнее, чем сама выручка. Это "
                  "ошибка в расчёте?",
        "датасет": f"коэффициент вариации выручки {cv_revenue:.1%}, ARPU {cv_arpu:.1%}",
        "неверный_ответ": "да, отношение должно быть стабильнее компонентов",
        "правильный_ответ": f"не обязательно ошибка: отношение двух шумных величин "
                           f"может иметь более высокую относительную изменчивость, чем "
                           f"любая из компонент, особенно при небольшой изменчивости "
                           f"знаменателя — здесь ARPU ({cv_arpu:.1%}) волатильнее выручки "
                           f"({cv_revenue:.1%})",
        "число": round(cv_arpu - cv_revenue, 4),
    }


def trap_20_novelty_effect():
    """Эффект новизны затухает — короткий тест переоценивает долгосрочный эффект."""
    week1_lift = 0.18
    week4_lift = 0.03
    return {
        "вопрос": f"Новая фича дала +{week1_lift:.0%} к вовлечённости в первую неделю. "
                  f"Можно экстраполировать этот прирост на квартал?",
        "датасет": f"неделя 1: +{week1_lift:.0%}, неделя 4: +{week4_lift:.0%} "
                   f"(типичная форма затухания эффекта новизны)",
        "неверный_ответ": f"да, эффект +{week1_lift:.0%} устойчив",
        "правильный_ответ": f"нет — падение с {week1_lift:.0%} до {week4_lift:.0%} за "
                           f"4 недели типично для эффекта новизны: пользователи пробуют "
                           f"новое из любопытства, часть эффекта исчезает по мере "
                           f"привыкания; тест должен идти достаточно долго, чтобы "
                           f"отделить устойчивый эффект от временного всплеска интереса",
        "число": round(week1_lift - week4_lift, 3),
    }


