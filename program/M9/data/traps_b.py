"""Ловушки группы B — значимость, множественные сравнения, тестирование
гипотез (step-02.md, 10 штук). Формат и правило SEED — как в traps_a.py."""

import random
import statistics
from math import sqrt

SEED = 20260824


def z_test(a, b):
    pa, pb = statistics.mean(a), statistics.mean(b)
    se = sqrt(pa * (1 - pa) / len(a) + pb * (1 - pb) / len(b))
    return (pa - pb) / se if se else 0, pa, pb


def trap_11_pvalue_misread():
    """p=0.03 не значит «вероятность, что H0 верна, — 3%»."""
    random.seed(SEED + 1000)
    control = [random.random() < 0.10 for _ in range(400)]
    treatment = [random.random() < 0.135 for _ in range(400)]
    z, pa, pb = z_test(control, treatment)
    return {
        "вопрос": "Тест дал p=0.03. Значит, вероятность, что эффекта нет, — 3%?",
        "датасет": f"control конверсия {pa:.1%} (n=400), treatment {pb:.1%} (n=400), z={z:.2f}",
        "неверный_ответ": "да, вероятность отсутствия эффекта — 3%",
        "правильный_ответ": "нет: p-value — вероятность увидеть такую или более "
                           "экстремальную разницу, ЕСЛИ эффекта на самом деле нет "
                           "(H0 верна); это не вероятность самой H0 при данных "
                           "наблюдениях — для последнего нужен байесовский расчёт с "
                           "априорной вероятностью",
        "число": round(z, 2),
    }


def trap_12_underpowered():
    """Отсутствие значимости при малой выборке не значит «эффекта нет»."""
    random.seed(SEED + 1)
    control = [random.random() < 0.10 for _ in range(40)]
    treatment = [random.random() < 0.14 for _ in range(40)]
    z, pa, pb = z_test(control, treatment)
    return {
        "вопрос": f"На выборке 40+40 разница конверсии {pb-pa:+.1%} незначима "
                  f"(z={z:.2f}). Можно заключить, что варианты равнозначны?",
        "датасет": f"control {pa:.1%} (n=40), treatment {pb:.1%} (n=40)",
        "неверный_ответ": "да, разница не значима — варианты одинаковы",
        "правильный_ответ": "нет: отсутствие значимости при n=40 может означать "
                           "недостаточную мощность теста, а не отсутствие эффекта — "
                           "нужен расчёт необходимого размера выборки заранее, а "
                           "не постфактум трактовка null-результата как доказательства "
                           "равенства",
        "число": round(z, 2),
    }


def trap_13_bonferroni_needed():
    """20 метрик проверены разом без поправки — сколько ложных ожидать."""
