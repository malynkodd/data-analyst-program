def trap_14_simpson_ab():
    """Simpson's paradox: вариант хуже в каждом сегменте, но лучше в целом."""
    desktop_a, desktop_b = (40, 400), (55, 500)   # (конверсии, n)
    mobile_a, mobile_b = (200, 2000), (140, 1500)
    desktop_rate_a, desktop_rate_b = desktop_a[0]/desktop_a[1], desktop_b[0]/desktop_b[1]
    mobile_rate_a, mobile_rate_b = mobile_a[0]/mobile_a[1], mobile_b[0]/mobile_b[1]
    total_a = (desktop_a[0]+mobile_a[0]) / (desktop_a[1]+mobile_a[1])
    total_b = (desktop_b[0]+mobile_b[0]) / (desktop_b[1]+mobile_b[1])
    return {
        "вопрос": "Вариант B хуже A и на desktop, и на mobile по отдельности. Может ли B "
                  "быть лучше A в общем отчёте?",
        "датасет": f"desktop: A {desktop_rate_a:.1%} (n={desktop_a[1]}), "
                   f"B {desktop_rate_b:.1%} (n={desktop_b[1]}); "
                   f"mobile: A {mobile_rate_a:.1%} (n={mobile_a[1]}), "
                   f"B {mobile_rate_b:.1%} (n={mobile_b[1]})",
        "неверный_ответ": "нет, если хуже в обеих группах — хуже и в сумме",
        "правильный_ответ": f"да: общий A {total_a:.1%}, общий B {total_b:.1%} — "
                           f"парадокс Симпсона, доли трафика desktop/mobile разные между "
                           f"вариантами (B получил больше desktop-трафика, где конверсия "
                           f"ниже у обоих), и агрегат меняет знак",
        "число": round(total_b - total_a, 4),
    }


def trap_15_confidence_interval_width():
    """Широкий доверительный интервал важнее точечной оценки эффекта."""
    random.seed(SEED + 2000)
    n = 25
    a = [random.gauss(500, 300) for _ in range(n)]
    b = [random.gauss(560, 300) for _ in range(n)]
    diff = statistics.mean(b) - statistics.mean(a)
    se = sqrt(statistics.variance(a)/n + statistics.variance(b)/n)
    ci_low, ci_high = diff - 1.96*se, diff + 1.96*se
    return {
        "вопрос": f"Средняя выручка выросла на {diff:.0f} грн. Внедряем изменение на всех?",
        "датасет": f"n=25 в каждой группе, разница средних {diff:.0f} грн, "
                   f"95% ДИ [{ci_low:.0f}; {ci_high:.0f}]",
        "неверный_ответ": "да, рост есть — внедряем",
        "правильный_ответ": f"доверительный интервал [{ci_low:.0f}; {ci_high:.0f}] "
                           f"включает 0 — точечная оценка положительна, но данных "
                           f"недостаточно, чтобы исключить нулевой или отрицательный "
                           f"эффект; точечное число без интервала вводит в заблуждение",
        "число": round(ci_low, 0),
    }


def trap_16_multiple_testing_over_time():
    """Ежедневная проверка одной и той же метрики 30 дней подряд."""
    random.seed(SEED + 3)
    hits = 0
    for _ in range(30):
        a = [random.random() < 0.10 for _ in range(50)]
        b = [random.random() < 0.10 for _ in range(50)]
        z, _, _ = z_test(a, b)
        if abs(z) > 1.96:
            hits += 1
    return {
        "вопрос": "Метрику без реального эффекта проверяли на значимость 30 дней подряд "
                  "разными случайными выборками. Сколько дней в среднем покажут ложную "
                  "значимость?",
        "датасет": f"30 независимых проверок без эффекта, порог 0.05: сработало {hits}",
        "неверный_ответ": "0, если эффекта нет — значимость не появится",
        "правильный_ответ": f"ожидаемо около {30*0.05:.1f} ложных срабатываний из 30 "
                           f"(в этом прогоне — {hits}); при ежедневном мониторинге без "
                           f"поправки на множественность рано или поздно появится "
                           f"случайная значимость просто по числу попыток",
        "число": hits,
    }


def trap_17_correlation_pvalue_confused():
    """Значимая, но слабая корреляция не значит практическую важность."""
    random.seed(SEED + 4)
    n = 500
    x = [random.gauss(0, 1) for _ in range(n)]
    y = [0.09 * xi + random.gauss(0, 1) for xi in x]
    mean_x, mean_y = statistics.mean(x), statistics.mean(y)
    cov = sum((xi-mean_x)*(yi-mean_y) for xi, yi in zip(x, y)) / n
    r = cov / (statistics.pstdev(x) * statistics.pstdev(y))
    t = r * sqrt((n-2) / (1 - r**2))
    return {
        "вопрос": f"На выборке {n} наблюдений корреляция r={r:.2f}, статистически "
                  f"значима (t={t:.1f}). Стоит ли строить на этом факторе стратегию?",
        "датасет": f"n={n}, r={r:.2f}",
        "неверный_ответ": "да, значимость подтверждена — фактор важен",
        "правильный_ответ": f"статистическая значимость при большом n почти неизбежна "
                           f"даже для слабой связи (r={r:.2f} объясняет лишь "
                           f"{r**2:.1%} дисперсии) — значимость отвечает на вопрос "
                           f"«связь отлична от нуля», не на вопрос «связь достаточно "
                           f"сильна, чтобы на неё полагаться»",
        "число": round(r**2, 3),
    }


