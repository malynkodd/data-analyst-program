def trap_23_pre_period_imbalance():
    """Группы неравны ещё ДО начала теста — эффект не приписать вмешательству."""
    random.seed(SEED + 1)
    pre_a = [random.gauss(1000, 100) for _ in range(40)]
    pre_b = [random.gauss(1080, 100) for _ in range(40)]
    diff_pre = statistics.mean(pre_b) - statistics.mean(pre_a)
    return {
        "вопрос": f"После теста treatment показал выручку выше control на 120 грн. Это "
                  f"эффект изменения?",
        "датасет": f"выручка ДО начала теста (когда обе группы ещё видели одно и то же): "
                   f"control {statistics.mean(pre_a):.0f}, treatment {statistics.mean(pre_b):.0f}",
        "неверный_ответ": "да, разница 120 грн — эффект изменения",
        "правильный_ответ": f"группы уже расходились на {diff_pre:.0f} грн ДО теста — "
                           f"рандомизация не гарантирует идеального равенства на малых "
                           f"выборках; правильная оценка эффекта — разница разниц "
                           f"(after − before) для каждой группы, а не сырая разница "
                           f"итоговых значений",
        "число": round(diff_pre, 0),
    }


