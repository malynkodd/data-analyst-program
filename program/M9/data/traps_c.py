def trap_28_effect_size_vs_significance():
    """Статистически значимый, но практически ничтожный эффект.

    Пропорции здесь заданы точно (не смоделированы через random) — при
    n=100000 на группу шум одной симуляции сам по себе сравним с эффектом
    0.3 п.п., и результат неустойчив от запуска к запуску; для
    иллюстрации «сходится ли порог значимости» нужны точные p, а не их
    шумная оценка.
    """
    n = 100000
    pa, pb = 0.100, 0.103
    se = sqrt(pa*(1-pa)/n + pb*(1-pb)/n)
    z = (pb-pa)/se if se else 0
    return {
        "вопрос": f"На выборке {n}+{n} тест дал z={z:.1f} (значимо). Внедрять изменение?",
        "датасет": f"control {pa:.2%}, treatment {pb:.2%}, абсолютная разница "
                   f"{pb-pa:.2%}",
        "неверный_ответ": "да, значимость подтверждена",
        "правильный_ответ": f"значимость — не то же самое, что польза для бизнеса: "
                           f"абсолютная разница всего {pb-pa:.2%} может не окупать "
                           f"затрат на внедрение и поддержку изменения; при очень "
                           f"больших выборках даже пренебрежимо малый эффект становится "
                           f"статистически значимым — решение требует сравнения размера "
                           f"эффекта со стоимостью изменения, не только p-value",
        "число": round(pb - pa, 4),
    }


def trap_29_multiple_metrics_cherry_pick():
    """Выбор 'победившей' метрики постфактум из многих измеренных."""
    random.seed(SEED + 3)
    metrics = {}
    for name in ["конверсия", "средний_чек", "время_на_сайте", "возвраты",
                "клики_на_баннер", "открытия_email", "добавления_в_корзину"]:
        a = [random.gauss(100, 20) for _ in range(40)]
        b = [random.gauss(100, 20) for _ in range(40)]  # эффекта нет нигде
        diff = statistics.mean(b) - statistics.mean(a)
        se = sqrt(statistics.variance(a)/40 + statistics.variance(b)/40)
        z = diff/se if se else 0
        metrics[name] = z
    winner = max(metrics, key=lambda k: abs(metrics[k]))
    return {
        "вопрос": f"Из 7 измеренных метрик тест анонсирован как успешный по метрике "
                  f"«{winner}» (z={metrics[winner]:.2f}). Остальные 6 не изменились. "
                  f"Отчёт готов к презентации?",
        "датасет": f"7 метрик без реального эффекта ни в одной; максимальный |z| = "
                   f"{abs(metrics[winner]):.2f} у «{winner}»",
        "неверный_ответ": "да, нашли метрику, где эффект есть",
        "правильный_ответ": f"нет — при проверке 7 метрик без поправки на "
                           f"множественность вероятность найти хотя бы одну случайно "
                           f"значимую заметно выше 5%; основная метрика теста должна "
                           f"быть выбрана ДО запуска, а не постфактум из тех, что "
                           f"«сработали»",
        "число": round(abs(metrics[winner]), 2),
    }


def trap_30_absolute_vs_relative():
    """Относительный прирост звучит внушительно на маленькой базе."""
    base_rate = 0.002
    new_rate = 0.003
    relative = (new_rate - base_rate) / base_rate
    return {
        "вопрос": f"Конверсия выросла с {base_rate:.1%} до {new_rate:.1%} — это "
                  f"«+{relative:.0%}»! Заголовок отчёта корректен?",
        "датасет": f"база {base_rate:.1%}, после {new_rate:.1%}, относительный "
                   f"прирост {relative:.0%}",
        "неверный_ответ": f"да, рост {relative:.0%} — впечатляющий результат",
        "правильный_ответ": f"формально верно, но вводит в заблуждение без абсолютных "
                           f"чисел: {relative:.0%} звучит крупно, а абсолютный прирост "
                           f"— {new_rate-base_rate:.1%} (1 дополнительная конверсия на "
                           f"1000 показов) — заголовок должен нести оба числа, не только "
                           f"относительное",
        "число": round(relative, 2),
    }


