def trap_25_sample_ratio_mismatch():
    """SRM — фактическое разбиение трафика отличается от заданного, тест недействителен."""
    from math import comb
    n_a, n_b = 5300, 4700
    expected = 5000
    chi2 = ((n_a - expected)**2)/expected + ((n_b - expected)**2)/expected
    return {
        "вопрос": f"Задано разбиение 50/50, по факту в тесте {n_a} против {n_b} "
                  f"пользователей. Разница мала (6%) — можно анализировать результаты как есть?",
        "датасет": f"ожидалось 5000/5000, получено {n_a}/{n_b}, chi2={chi2:.1f}",
        "неверный_ответ": "да, 6% — в пределах случайных колебаний",
        "правильный_ответ": f"нет: это классический Sample Ratio Mismatch (SRM), "
                           f"chi2={chi2:.1f} на 1 степени свободы (порог значимости "
                           f"~3.84) намного выше случайного — при истинном 50/50 такое "
                           f"расхождение крайне маловероятно; SRM указывает на баг в "
                           f"системе распределения трафика (например, разное время "
                           f"загрузки вариантов теряет часть пользователей одной из "
                           f"групп) — результаты теста при SRM не заслуживают доверия "
                           f"до устранения причины",
        "число": round(chi2, 1),
    }


