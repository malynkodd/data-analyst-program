import random
import statistics
from math import sqrt

SEED = 20260825


def trap_21_unequal_allocation():
    """Неравное распределение трафика само по себе не искажает результат, но снижает мощность."""
    random.seed(SEED + 2)
    a = [random.random() < 0.10 for _ in range(1800)]
    b = [random.random() < 0.115 for _ in range(200)]
    pa, pb = statistics.mean(a), statistics.mean(b)
    se = sqrt(pa*(1-pa)/len(a) + pb*(1-pb)/len(b))
    z = (pb-pa)/se if se else 0
    return {
        "вопрос": f"Трафик разделён 90/10 (control/treatment) вместо 50/50. Это делает "
                  f"тест некорректным?",
        "датасет": f"control n={len(a)} ({pa:.1%}), treatment n={len(b)} ({pb:.1%}), z={z:.2f}",
        "неверный_ответ": "да, неравное разбиение искажает результат",
        "правильный_ответ": f"неравное разбиение само по себе не искажает оценку эффекта "
                           f"(она остаётся несмещённой), но снижает статистическую "
                           f"мощность — при том же общем трафике меньшая группа даёт "
                           f"более широкий доверительный интервал, здесь z={z:.2f} "
                           f"недостаточно для уверенного вывода при этой разнице групп",
        "число": round(z, 2),
    }


